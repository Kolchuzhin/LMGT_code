function EPLOT(CT,ET,el,tcolor,key)
%=========================================================================%
% PURPOSE:
%           plot volume or #el defined by CT,ET
% INPUT:
%           CT,ET,el,tcolor,
%           key=4 - 2D 4-Node
%           key=8 - 3D 8-Node
%
% OUTPUT:
%           plot
%-------------------------------------------------------------------------%
% written by Kolchuzhin V.A., LMGT, TU Chemnitz, 13.09.2006 15:45
% ver. 0.2 18.02.2009 16:17
%=========================================================================%
if nargin==0 % self test
	%--------------------------
	CT=[...
		1 0 0 0
		2 1 0 0
		3 1 1 0
		4 0 1 0
		5 0 0 1
		6 1 0 1
		7 1 1 1
		8 0 1 1];
	ET=[1 2 3 4 5 6 7 8]; el=1; key=8;
	%--------------------------
	CT=[...
		1 0 0 0
		2 1 0 0
		3 1 1 0
		4 0 1 0];
	ET=[1 2 3 4]; el=1; key=4;
	%--------------------------
	tcolor=[.8 .8 .6];
end
%-------------------%
if nargin==2
    el=[1:numel(ET(:,1))];	% all elements
    tcolor=[.8 .8 .6];
    key=8;
end
%=========================================================================%
L8=[1 5 1 4 1 2; 2 6 2 3 4 3; 3 7 6 7 8 7; 4 8 5 8 5 6;]; % 3D 8-Node
L4=[1;           2;           3;           4;];           % 2D 4-Node

          L=L8; jf=6;
if key==4       jf=1; end
%-------------------------------------------------------------------------%
for k=1:numel(el)
	for i=1:4
		for j=1:jf
			x(i,j) = CT(ET(el(k),L(i,j)),2);
			y(i,j) = CT(ET(el(k),L(i,j)),3);
			z(i,j) = CT(ET(el(k),L(i,j)),4);
		end
	end
	patch(x,y,z,tcolor);
	%fill3(x,y,z,tcolor);
end
view(3);
%=========================================================================%
return
%=========================================================================%